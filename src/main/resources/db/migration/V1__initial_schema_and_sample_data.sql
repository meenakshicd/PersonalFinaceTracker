CREATE TABLE clients (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    phone_number VARCHAR(32) NOT NULL,
    email VARCHAR(254) NOT NULL,
    auth_subject VARCHAR(255) UNIQUE
);

CREATE TABLE accounts (
    id VARCHAR(64) PRIMARY KEY,
    name VARCHAR(120) NOT NULL,
    balance NUMERIC(19, 2) NOT NULL,
    currency VARCHAR(3) NOT NULL,
    client_id BIGINT REFERENCES clients (id)
);

CREATE TABLE transactions (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id VARCHAR(64) NOT NULL REFERENCES accounts (id),
    description VARCHAR(240) NOT NULL,
    amount NUMERIC(19, 2) NOT NULL,
    date DATE NOT NULL,
    transaction_type VARCHAR(8) NOT NULL
        CHECK (transaction_type IN ('INCOME', 'EXPENSE', 'TRANSFER')),
    category VARCHAR(32)
);

CREATE INDEX idx_accounts_client_id ON accounts (client_id);
CREATE INDEX idx_transactions_date_id ON transactions (date DESC, id DESC);
CREATE INDEX idx_transactions_account_type_date
    ON transactions (account_id, transaction_type, date);

CREATE TABLE monthly_spending_limits (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    client_id BIGINT NOT NULL REFERENCES clients (id),
    month VARCHAR(7) NOT NULL,
    category VARCHAR(32) NOT NULL,
    limit_amount NUMERIC(19, 2) NOT NULL,
    CONSTRAINT uk_monthly_spending_limit UNIQUE (client_id, month, category)
);

CREATE INDEX idx_monthly_spending_limits_client_month
    ON monthly_spending_limits (client_id, month);
